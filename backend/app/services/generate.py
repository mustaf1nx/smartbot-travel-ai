from ..config import settings

PROMPT_TMPL = """Ты — копирайтер в туризме Казахстана. Напиши 150-300 слов описания для каталога mytravel.kz.
Учитывай нишу: {category}. Локация: {city_region}. 
Инфраструктура: {infra}. Уникальные преимущества: {unique}.
Стиль: увлекательно, ясно, без воды. Без эмодзи. Русский язык."""

async def generate_description(item: dict) -> str:
    # Для демо: локальный генератор (без реального вызова), чтобы запускалось офлайн.
    # На хакатоне можно заменить на реальный вызов LLM провайдера.
    text = PROMPT_TMPL.format(
        category=item.get("category","other"),
        city_region=item.get("address","Казахстан"),
        infra=", ".join(item.get("infra",[])) or "базовые удобства",
        unique=item.get("website") or "уникальная природа и аутентичная атмосфера"
    )
    # Возвращаем заглушку: в реальном вызове отправляем text в LLM, берем completion
    return ("Расположенный в сердце приуральских просторов объект размещения предлагает спокойный отдых "
            "вблизи природы. Здесь удобно семьям и путешественникам, кто ценит приватность и чистый воздух. "
            "Гости оценят удобства: " + ", ".join(item.get("infra",[])) + 
            ". Близость к ключевым локациям региона позволит строить насыщенные маршруты. "
            "Хозяева уделяют внимание деталям, а номерной фонд подходит как для коротких поездок, так и "
            "для длительного пребывания. Это место c крепкой локальной идентичностью и доброжелательным сервисом.")
